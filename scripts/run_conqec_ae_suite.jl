function usage(io::IO=stdout)
    print(io, """
ConQEC AE suite summary

Usage:
  julia --project=. scripts/run_conqec_ae_suite.jl [--backend z3] [--solver-path z3] [--subject NAME] [--witness-dir DIR]
  julia --project=. scripts/run_conqec_ae_suite.jl --list-subjects

Options:
  --subject NAME     Run one paper subject by registry label or subject_name.
  --quick            Run the AE smoke subset used by unit tests.
  --witness-dir DIR   Directory for witnesses generated by this run.
                      Default: artifacts/witnesses
$(conqec_backend_usage())
  --list-subjects     Print the shared paper/AE subject registry and exit.
  -h, --help          Show this help text.

The suite runs the three-qubit bit-flip, phase-flip, Steane CSS, surface-code
kernel, distance-5 repetition-code, and repeated-round repetition-code subjects
from scratch, prints an aligned smoke-summary table, and prints witness
diagnostics for every discovered bug. The Julia code uses only Base/stdlib and
ConQEC's local source files; solving backends use the configured command-line SMT solver.
""")
end

function parse_args(args::Vector{String})
    opts = conqec_merge_backend_defaults!(Dict{String,String}())
    idx = 1
    while idx <= length(args)
        arg = args[idx]
        if arg == "--help" || arg == "-h"
            opts["help"] = "true"
        elseif arg == "--list-subjects"
            opts["list-subjects"] = "true"
        elseif arg == "--quick"
            opts["quick"] = "true"
        elseif startswith(arg, "--")
            body = arg[3:end]
            if occursin("=", body)
                key_value = split(body, "="; limit=2)
                opts[key_value[1]] = key_value[2]
            else
                idx == length(args) && error("missing value for $(arg)")
                value = args[idx + 1]
                startswith(value, "--") && error("missing value for $(arg)")
                opts[body] = value
                idx += 1
            end
        else
            error("unexpected argument: $(arg)")
        end
        idx += 1
    end

    for key in keys(opts)
        key in ("help", "list-subjects", "quick", "subject", "witness-dir") ||
            conqec_is_backend_option_key(key) ||
            error("unknown option --$(key)")
    end
    conqec_validate_backend_options!(opts)
    return opts
end

function print_subject_registry(io::IO=stdout)
    println(io, "ConQEC paper subjects")
    for config in AE_SUBJECTS
        println(io, subject_name(config.subject), " max_tests=", config.max_tests)
    end
end

function subject_configs_from_options(opts::Dict{String,String})
    haskey(opts, "quick") && haskey(opts, "subject") &&
        error("Pass either --quick or --subject, not both")
    haskey(opts, "quick") && return quick_ae_subject_configs()
    haskey(opts, "subject") || return AE_SUBJECTS
    try
        return (paper_subject_config_by_name(opts["subject"]),)
    catch err
        err isa ErrorException || rethrow()
        valid = join(
            (config.label == subject_name(config.subject) ?
                config.label :
                string(config.label, " (", subject_name(config.subject), ")")
             for config in AE_SUBJECTS),
            ", ",
        )
        error("unknown paper subject: $(opts["subject"]). " *
              "Use --list-subjects to inspect the registry. Valid subjects: $(valid)")
    end
end

function default_witness_dir()
    return joinpath(@__DIR__, "..", "artifacts", "witnesses")
end

function run_report(config, witness_dir::AbstractString, opts::AbstractDict)
    max_weight = conqec_backend_max_weight(opts)
    result = run_concolic_subject(
        config.subject;
        max_tests=config.max_tests,
        max_fault_weight=max_weight,
        solver=conqec_solver_for_subject(config.subject, opts; max_weight=max_weight),
        witness_dir=witness_dir,
        stop_on_bug=true,
    )
    divergence = result.witness === nothing ?
        "none" :
        String(result.witness["earliest_divergence_stage"])
    return (
        label=config.label,
        subject=config.subject,
        result=result,
        divergence=divergence,
    )
end

function cell_text(value)
    value === nothing && return "none"
    value isa Bool && return value ? "true" : "false"
    return String(string(value))
end

function print_table(io::IO, headers::Vector{String}, rows::Vector{Vector{String}})
    widths = [length(header) for header in headers]
    for row in rows
        for (idx, cell) in enumerate(row)
            widths[idx] = max(widths[idx], length(cell))
        end
    end

    println(io, join((rpad(headers[idx], widths[idx]) for idx in eachindex(headers)), "  "))
    println(io, join((repeat("-", widths[idx]) for idx in eachindex(headers)), "  "))
    for row in rows
        println(io, join((rpad(row[idx], widths[idx]) for idx in eachindex(row)), "  "))
    end
end

function summary_row(report)
    result = report.result
    return [
        report.subject.name,
        string(result.generated_tests),
        string(length(result.unique_syndromes)),
        cell_text(result.bug_found),
        report.divergence,
        result.witness_path === nothing ? "none" : result.witness_path,
    ]
end

function recovery_summary(action::AbstractDict)
    summary = string(action["pauli"], "@", action["target"])
    inferred_round = get(action, "inferred_round", nothing)
    inferred_round === nothing && return summary
    return string(summary, " (round ", inferred_round, ")")
end

function fault_pattern_summary(witness::AbstractDict)
    active = String[]
    for item in witness["fault_pattern"]
        get(item, "active", false) || continue
        push!(active, String(item["label"]))
    end
    return isempty(active) ? "none" : join(active, ",")
end

function syndrome_summary(witness::AbstractDict)
    observed = witness["observed_syndrome"]
    parts = String[]
    for key in sort!(collect(keys(observed)), by=string)
        push!(parts, string(key, "=", observed[key] ? "1" : "0"))
    end
    return join(parts, ",")
end

function syndrome_diagnostics(witness::AbstractDict)
    metadata = get(witness, "metadata", Dict{String,Any}())
    return get(metadata, "syndrome_diagnostics", nothing)
end

function decoder_diagnostics(witness::AbstractDict)
    metadata = get(witness, "metadata", Dict{String,Any}())
    return get(metadata, "decoder_diagnostics", nothing)
end

function print_example_summary(io::IO, report)
    result = report.result
    println(io, "Example")
    println(io, "-------")
    println(io, "three-qubit bit-flip seeded decoder example")
    println(io, "equivalent script: example/conqec_bitflip.jl")
    println(io, "subject: ", report.subject.name)
    println(io, "bug_found: ", result.bug_found)
    println(io, "earliest_divergence: ", report.divergence)
    println(io, "witness: ", result.witness_path === nothing ? "none" : result.witness_path)
    if length(result.traces) >= 2
        first_trace = result.traces[1]
        witness_trace = result.traces[end]
        println(io, "exploration: ",
            assignment_key(first_trace.fault_vars, first_trace.fault_assignments),
            " -> ",
            assignment_key(witness_trace.fault_vars, witness_trace.fault_assignments))
    end
end

function print_witness_diagnostics(io::IO, report)
    result = report.result
    result.witness === nothing && return

    witness = result.witness
    actual_recovery = witness["recovery_actually_applied"][1]
    expected_recovery = witness["expected_recovery"]
    logical_verdicts = witness["logical_verdicts"]
    diagnostics = syndrome_diagnostics(witness)
    decoder_info = decoder_diagnostics(witness)

    println(io, "subject: ", report.subject.name)
    println(io, "  witness: ", result.witness_path)
    println(io, "  fault pattern: ", fault_pattern_summary(witness))
    println(io, "  triggered oracles: ", stored_oracle_summary_text(witness))
    if diagnostics === nothing
        println(io, "  observed syndrome: ", syndrome_summary(witness))
    else
        println(io, "  syndrome observed/expected: ",
            diagnostics["observed"], " / ", diagnostics["expected"])
        println(io, "  observed syndrome bits: ", syndrome_summary(witness))
    end
    if decoder_info !== nothing && haskey(decoder_info, "observed_history")
        println(io, "  observed history: ", decoder_info["observed_history"])
        println(io, "  decoder history used: ", decoder_info["decoder_history_used"])
        println(io, "  history_mismatch: ", decoder_info["history_mismatch"])
    end
    measurement_info = get(get(witness, "metadata", Dict{String,Any}()),
        "measurement_misuse", nothing)
    if measurement_info !== nothing
        println(io, "  measurement misuse: observed s23=",
            measurement_info["observed_s23_expr"],
            ", expected s23=",
            measurement_info["expected_s23_expr"])
    end
    println(io, "  syndrome_mismatch: ",
        get(logical_verdicts, "syndrome_mismatch", false))
    println(io, "  decoder actual/expected: ",
        witness["decoder_output"], " / ", witness["expected_decoder_output"])
    println(io, "  recovery actual/expected: ",
        recovery_summary(actual_recovery), " / ", recovery_summary(expected_recovery))
    println(io, "  missing_recovery_branch: ",
        logical_verdicts["missing_recovery_branch"])
    if haskey(witness, "minimization")
        minimization = witness["minimization"]
        println(io, "  minimized fault weight: ",
            minimization["original_fault_weight"], " -> ",
            minimization["minimized_fault_weight"])
    end
    println(io, "  earliest_divergence: ", witness["earliest_divergence_stage"])
end

function print_report(io::IO, reports, witness_dir::AbstractString)
    println(io, "ConQEC AE suite")
    println(io, "===============")
    println(io, "witness_dir: ", witness_dir)
    println(io)

    seeded_reports = filter(report -> report.label == "bitflip_buggy_decoder", collect(reports))
    if !isempty(seeded_reports)
        print_example_summary(io, only(seeded_reports))
        println(io)
    end

    println(io, "Smoke subjects")
    println(io, "--------------")
    headers = ["subject", "tests", "syndromes", "bug_found", "earliest_divergence", "witness_path"]
    rows = [summary_row(report) for report in reports]
    print_table(io, headers, rows)
    println(io)

    println(io, "Witness replay diagnostics")
    println(io, "--------------------------")
    any_witness = false
    for report in reports
        report.result.witness === nothing && continue
        any_witness = true
        print_witness_diagnostics(io, report)
    end
    any_witness || println(io, "none")
end

function main(args::Vector{String}=ARGS)
    opts = parse_args(args)
    if haskey(opts, "help")
        usage()
        return 0
    end
    if haskey(opts, "list-subjects")
        print_subject_registry()
        return 0
    end

    witness_dir = conqec_witness_dir(opts, get(opts, "witness-dir", default_witness_dir()))
    subject_configs = subject_configs_from_options(opts)
    reports = [run_report(config, witness_dir, opts) for config in subject_configs]
    print_report(stdout, reports, witness_dir)
    return 0
end

if abspath(PROGRAM_FILE) == abspath(@__FILE__)
    try
        exit(main(ARGS))
    catch err
        println(stderr, "error: ", sprint(showerror, err))
        println(stderr)
        usage(stderr)
        exit(1)
    end
end
